/**
 * The worker side of the data protocol (protocol.ts): a plain function of `postMessage`, so the same code
 * runs in the Web Worker (data.worker.ts) and in-process in tests. Requests are handled one at a time, in
 * order; a Scene request that a newer one has replaced by the time its snapshot is ready is skipped (the page
 * has already dropped it). The last snapshot's Graph is kept, so switching lenses or filters only builds a
 * Scene. A view's timeline `tick` draws that day of the snapshot (timeline/worker/source.ts): its
 * Graph is built once and kept with the last few days'. The requests that follow a Scene (choices, details,
 * search, locate, reveal) name the day they read, the day on screen (`day`, protocol.ts `DayRef`), so
 * an answer is that day's whatever Scene the worker built last. A Scene request may name a day to compare the
 * drawn day with: its answer then carries the diff of the two days (diff/tickDiff.ts) and its Scene
 * the ghosts of what the view no longer draws; `changes` answers what changed about one node between two days
 * it names (drawer/changes.ts). The Scenes a Scene request and its diff build are kept per Graph
 * (sceneMemo.ts), so a timeline step builds only the views of the day it moves to; and what the Graph
 * builder works out per asset is kept per asset (`BuildMemo`), so a day's Graph evaluates the catalog's rules
 * only for the assets the day changed (historyRead.ts: a day's unchanged assets are the objects an earlier
 * day read). A Scene drawn without a diff on a stored history's timeline has its open view (the one the next
 * step's diff counts chips with) built once no request is waiting (`WARM_AFTER_MS`), from the drawn view's
 * preparation: the first step back from the snapshot's own day then finds it built too. That reads no data
 * and builds no other day.
 */

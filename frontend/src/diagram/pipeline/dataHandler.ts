export class DataError extends Error {
  readonly code: DataErrorCode;

  constructor(code: DataErrorCode, message: string) {
    super(message);
    this.name = 'DataError';
    this.code = code;
  }
}

/** Loads the snapshot a view names, reporting its stages. */
export type SnapshotLoader = (ref: SnapshotRef, onStage: (stage: DataStage) => void) => Promise<Snapshot>;

/** The demo generator (demo.ts), loaded on first use: a stored snapshot is drawn without it (ADR 0029). */
function demoModule(): Promise<typeof import('./demo')> {
  return import('./demo');
}

/**
 * The demo organisations (ADR 0014) as the app reads any export: generated by `@gcportrait/demo-data` as CAI NDJSON
 * and ingested by `@gcportrait/ingest`, read at the demo's day with a fixed clock and entropy, so the same
 * organisation always gives the same snapshot (and so the same diagram); demo.ts does both.
 */
export const loadDemoSnapshot: SnapshotLoader = async (ref, onStage) => {
  const size = ref.startsWith(DEMO_REF_PREFIX) ? ref.slice(DEMO_REF_PREFIX.length) : undefined;
  if (!isDemoSize(size)) throw new DataError('unknown-snapshot', `No snapshot "${ref}" is available yet.`);
  onStage('generate');
  const demo = await demoModule();
  const history = demo.demoHistory(size);
  onStage('ingest');
  return demo.demoSnapshot(history);
};

/** The catalog's lenses in the model's order, with their titles (data, not a map in code). */
export function lensList(): LensInfo[] {
  return LENS_IDS.map((id) => ({
    id,
    title: catalog.lenses[id].title,
    description: catalog.lenses[id].description,
    defaultDetail: catalog.lenses[id].defaultDetail,
  }));
}

/**
 * The type names of a Scene's product-container zones, from the Graph (a Scene zone carries only its kind):
 * "Compute Engine instance group manager" names a managed instance group's zone better than "Container".
 */
export function zoneTypeNames(scene: Scene, graph: Graph): Record<string, string> {
  const names: Record<string, string> = {};
  const walk = (nodes: readonly SceneNode[]): void => {
    for (const node of nodes) {
      if (node.type !== 'zone') continue;
      const asset = node.kind === 'product-container' ? graph.nodes[node.id] : undefined;
      if (asset !== undefined) names[node.id] = cardTypeName(asset.product, asset.assetType);
      walk(node.children);
    }
  };
  walk(scene.children);
  return names;
}

/** The assets of a snapshot by name and its project index: what the console links are worked out from. */
export interface ConsoleSource {
  readonly assets: ReadonlyMap<string, Asset>;
  readonly ctx: RuleContext;
}

export function consoleSource(snapshot: Snapshot): ConsoleSource {
  return {
    assets: new Map(snapshot.assets.map((asset) => [asset.name, asset])),
    ctx: { projects: buildProjectIndex(snapshot.assets) },
  };
}

/**
 * The console action of every asset-backed node of a Scene (`consoleLinkFor` of the catalog engine,
 * the one place console URLs are built): its own page when its type's template renders, else its project's
 * console home; nothing for synthetic zones (regions, bundles) and assets outside any project without a
 * template. `types` is the catalog's type table (a test may strip a template from it).
 */
export function consoleLinks(
  scene: Scene,
  source: ConsoleSource,
  types: Pick<Catalog, 'types'> = catalog,
): Record<string, ConsoleLink> {
  const links: Record<string, ConsoleLink> = {};
  const walk = (nodes: readonly SceneNode[]): void => {
    for (const node of nodes) {
      const asset = source.assets.get(node.id);
      const link = asset === undefined ? undefined : consoleLinkFor(asset, types, source.ctx);
      if (link !== undefined) links[node.id] = link;
      if (node.type === 'zone') walk(node.children);
    }
  };
  walk(scene.children);
  return links;
}

interface Loaded {
  readonly ref: SnapshotRef;
  readonly snapshot: Snapshot;
  readonly graph: Graph;
  readonly console: ConsoleSource;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

function viewportOf(value: unknown): Viewport {
  if (!isRecord(value)) return { width: 1280, height: 800 };
  const width = typeof value['width'] === 'number' && value['width'] > 0 ? value['width'] : 1280;
  const height = typeof value['height'] === 'number' && value['height'] > 0 ? value['height'] : 800;
  return { width, height };
}

/** Parses a message from the page; anything else is a protocol error. */
function parseRequest(message: unknown): DataRequest | { readonly id: number; readonly error: string } {
  const id = isRecord(message) && typeof message['id'] === 'number' ? message['id'] : -1;
  if (!isRecord(message)) return { id, error: 'a request must be an object' };
  if (message['type'] === 'lenses') return { type: 'lenses', id };
  if (message['type'] === 'scene') {
    const spec = ViewSpecSchema.safeParse(message['spec']);
    if (!spec.success) return { id, error: 'the view is not a valid ViewSpec' };
    const diffFrom = parseDay(message['diffFrom']);
    if (diffFrom === 'invalid') return { id, error: 'the day to compare with is malformed' };
    return {
      type: 'scene',
      id,
      spec: spec.data,
      viewport: viewportOf(message['viewport']),
      ...(diffFrom === undefined ? {} : { diffFrom }),
    };
  }
  if (message['type'] === 'choices') {
    const ref = message['snapshot'];
    if (!isSnapshotRef(ref) || ref === '') return { id, error: 'the request names no snapshot' };
    const day = parseFollowUpDay(message['day']);
    if (day === null) return { id, error: 'the day is malformed' };
    return { type: 'choices', id, snapshot: ref, day };
  }
  if (message['type'] === 'details' || message['type'] === 'reveal' || message['type'] === 'changes') {
    const node = message['node'];
    if (typeof node !== 'string' || node === '') return { id, error: 'the request names no node' };
    if (message['type'] === 'changes') {
      const ref = message['snapshot'];
      if (!isSnapshotRef(ref) || ref === '') return { id, error: 'the request names no snapshot' };
      const since = parseDay(message['since']);
      const day = parseDay(message['day']);
      if (since === undefined || since === 'invalid' || day === undefined || day === 'invalid')
        return { id, error: 'the days to compare are malformed' };
      return { type: 'changes', id, snapshot: ref, node, since, day };
    }
    const day = parseFollowUpDay(message['day']);
    if (day === null) return { id, error: 'the day is malformed' };
    if (message['type'] === 'details') {
      const ref = message['snapshot'];
      if (!isSnapshotRef(ref) || ref === '') return { id, error: 'the request names no snapshot' };
      return { type: 'details', id, snapshot: ref, node, day };
    }
    const spec = ViewSpecSchema.safeParse(message['spec']);
    if (!spec.success || spec.data.snapshot === '') return { id, error: 'the view is not a valid ViewSpec' };
    return { type: 'reveal', id, spec: spec.data, viewport: viewportOf(message['viewport']), node, day };
  }
  if (message['type'] === 'search') {
    const query = parseSearchQuery(message['query']);
    return query === null ? { id, error: 'the search query is malformed' } : { type: 'search', id, query };
  }
  if (message['type'] === 'locate') {
    const query = parseLocateQuery(message['query']);
    if (query === null || query.spec.snapshot === '') return { id, error: 'the locate query is malformed' };
    return { type: 'locate', id, query };
  }
  if (message['type'] === 'demo') {
    const size = message['size'];
    return isDemoSize(size)
      ? { type: 'demo', id, size }
      : { id, error: `no demo organisation of size ${JSON.stringify(size)}` };
  }
  return { id, error: `unknown request type ${JSON.stringify(message['type'])}` };
}

/** What the scene builder reads besides the Graph and the view: the same for a Scene and a reveal. */
function sceneEnv(snapshot: Snapshot, viewport: Viewport): SceneEnv {
  return {
    readTime: snapshot.readTime,
    rootLabel: snapshot.scope.displayName ?? snapshot.scope.id,
    viewportBudget: viewportBudget(viewport.width, viewport.height),
  };
}

export interface DataHandlerEnvironment {
  readonly loadSnapshot?: SnapshotLoader;
  /**
   * Asked before the kept Graph is reused (a stored snapshot can be deleted while its Graph is kept): when it
   * answers differently than when `ref` was loaded, `ref` is loaded again. Absent, a kept Graph is always reused.
   */
  readonly snapshotVersion?: (ref: SnapshotRef) => Promise<string | null>;
  /** The catalog's type table for the console links (tests strip a template from it); the catalog's own. */
  readonly consoleTypes?: Pick<Catalog, 'types'>;
  /** The snapshots' other days; default: the demo organisations' histories only. */
  readonly ticks?: TickSource;
  /** The Scene memo (sceneMemo.ts; a test counts its builds); default: a new one with the catalog. */
  readonly scenes?: SceneMemo;
  /** How long the worker waits without a request before it builds a drawn view's open view; `WARM_AFTER_MS`. */
  readonly warmAfterMs?: number;
}

/** The Graphs of the loaded snapshot's other days that are kept (scrubbing back to one builds nothing). */
const KEPT_TICK_GRAPHS = 3;

/**
 * How long the data worker waits without a request before it builds the open view of a Scene drawn without a
 * diff: 0, a timer task, so the requests already received go first. The open view is usually finished from the
 * drawn view's preparation (sceneMemo.ts): about 5 ms on demo L and 25 ms on XL (Node), while the page lays the
 * drawing out. When the drawn view came from the memo and another view's preparation is the one kept (a lens switched
 * back to), it is prepared afresh: about 17 ms on L and 150 to 170 ms on XL. A request that arrives meanwhile waits
 * for it. Built later (at 200 ms of quiet), a first step taken at once would build it itself.
 */
export const WARM_AFTER_MS = 0;

export function createDataHandler(
  post: (response: DataResponse) => void,
  environment: DataHandlerEnvironment = {},
): (message: unknown) => void {
  const loadSnapshot = environment.loadSnapshot ?? loadDemoSnapshot;
  const ticks = environment.ticks ?? createTickSource();
  // The Scenes built per Graph: a timeline step's diff reuses the views built for the day before.
  const scenes = environment.scenes ?? createSceneMemo(catalog);
  // What the Graph builder worked out per asset: a history's days share their unchanged assets
  // (historyRead.ts), so a day's Graph evaluates the catalog's rules only for the assets that day changed.
  const graphMemo = new BuildMemo();
  const graphOf = (snapshot: Snapshot): Graph => buildGraph(snapshot, catalog, { memo: graphMemo });
  let loaded: Promise<Loaded> | null = null;
  // The loaded snapshot's other days by day and version, least recently used first.
  const tickGraphs = new Map<string, Promise<Loaded>>();
  let loadedRef: SnapshotRef | null = null;
  let loadedVersion: string | null = null;
  let latestScene = -1;
  // The newest search and locate request: an older one still queued is skipped, as the page dropped it.
  const latestSearch = { search: -1, locate: -1 };
  let queue: Promise<void> = Promise.resolve();
  // The open view to build at idle (`WARM_AFTER_MS`): the job, its timer, and the requests received so far.
  const warmAfter = environment.warmAfterMs ?? WARM_AFTER_MS;
  let warming: (() => void) | null = null;
  let warmTimer: ReturnType<typeof setTimeout> | undefined;
  let received = 0;

  /** (Re)starts the idle timer of the pending open view, or stops it when there is none. */
  const armWarming = (): void => {
    if (warmTimer !== undefined) clearTimeout(warmTimer);
    warmTimer = undefined;
    const job = warming;
    if (job === null) return;
    warmTimer = setTimeout(() => {
      warmTimer = undefined;
      const at = received;
      queue = queue.then(
        () => {
          // A request received since went first and started the timer again; a newer Scene dropped the job.
          if (warming !== job || received !== at) return;
          warming = null;
          try {
            job();
          } catch {
            // Nothing is kept: the next step's diff builds the view itself, and reports what fails.
          }
        },
        () => undefined,
      );
    }, warmAfter);
  };

  const graphFor = async (ref: SnapshotRef, id: number): Promise<Loaded> => {
    const version = environment.snapshotVersion === undefined ? null : await environment.snapshotVersion(ref);
    if (loaded !== null && loadedRef === ref && loadedVersion === version) return loaded;
    loadedRef = ref;
    loadedVersion = version;
    tickGraphs.clear();
    loaded = (async () => {
      const snapshot = await loadSnapshot(ref, (stage) => {
        post({ type: 'progress', id, stage });
      });
      post({ type: 'progress', id, stage: 'graph' });
      return { ref, snapshot, graph: graphOf(snapshot), console: consoleSource(snapshot) };
    })();
    // A failed load is not kept: the next request tries again.
    loaded.catch(() => {
      loaded = null;
      loadedRef = null;
    });
    return loaded;
  };

  /**
   * The Graph of snapshot `ref` on `day`, with the day it is (absent: the snapshot itself, which is drawn for
   * its own day, a day its timeline does not have, and a live day the page has not read yet).
   */
  const graphAt = async (
    ref: SnapshotRef,
    day: string | undefined,
    id: number,
  ): Promise<{ readonly base: Loaded; readonly loaded: Loaded; readonly tick?: string }> => {
    const base = await graphFor(ref, id);
    const resolved = day === undefined ? null : await ticks.resolve(ref, base.snapshot, day);
    if (resolved === null) return { base, loaded: base };
    const key = `${resolved.day} ${resolved.version}`;
    let entry = tickGraphs.get(key);
    if (entry === undefined) {
      const building = (async (): Promise<Loaded> => {
        post({ type: 'progress', id, stage: 'ingest' });
        const snapshot = await resolved.load();
        post({ type: 'progress', id, stage: 'graph' });
        return { ref, snapshot, graph: graphOf(snapshot), console: consoleSource(snapshot) };
      })();
      // A failed day is not kept: the next request tries again.
      building.catch(() => {
        if (tickGraphs.get(key) === building) tickGraphs.delete(key);
      });
      entry = building;
    }
    tickGraphs.delete(key);
    tickGraphs.set(key, entry);
    for (const old of tickGraphs.keys()) {
      if (tickGraphs.size <= KEPT_TICK_GRAPHS) break;
      tickGraphs.delete(old);
    }
    return { base, loaded: await entry, tick: resolved.day };
  };

  /**
   * The Graph of `ref` on the day a follow-up request names (the day on screen): the snapshot itself for its
   * own day, or a day its timeline does not have (any more), as the Scene request that drew it was answered.
   */
  const graphOn = async (ref: SnapshotRef, day: DayRef, id: number): Promise<Loaded> =>
    (await graphAt(ref, day.tick ?? undefined, id)).loaded;

  const handle = async (request: DataRequest): Promise<void> => {
    if (request.type === 'demo') {
      const { prepareDemo } = await demoModule();
      const prepared = await prepareDemo(request.size, (progress) => {
        post({ type: 'job-progress', id: request.id, progress });
      });
      post({ type: 'demo', id: request.id, prepared });
      return;
    }
    if (request.type === 'lenses') {
      post({ type: 'lenses', id: request.id, lenses: lensList() });
      return;
    }
    if (request.type === 'choices') {
      const { snapshot, graph } = await graphOn(request.snapshot, request.day, request.id);
      post({
        type: 'choices',
        id: request.id,
        choices: viewChoices(request.snapshot, snapshot, graph, catalog),
      });
      return;
    }
    if (request.type === 'details') {
      const { graph, console: source } = await graphOn(request.snapshot, request.day, request.id);
      const details = nodeDetails({ graph, ...source }, request.node, environment.consoleTypes ?? catalog);
      post({ type: 'details', id: request.id, details });
      return;
    }
    if (request.type === 'changes') {
      // Both days are built, or kept, like any day; their stages are not the page's to show (-1: no request of the
      // page). A day the timeline no longer has would be drawn as the snapshot itself: no comparison with it.
      const at = async (wanted: DiffFrom): Promise<ChangesDay | null> => {
        const tick = wanted.tick ?? undefined;
        const found = await graphAt(request.snapshot, tick, -1);
        if (found.tick !== tick) return null;
        const { snapshot, graph, console: source } = found.loaded;
        return { snapshot, graph, assets: source.assets, ...(tick === undefined ? {} : { tick }) };
      };
      const before = await at(request.since);
      const after = await at(request.day);
      post({
        type: 'changes',
        id: request.id,
        changes: before === null || after === null ? null : nodeChanges(before, after, request.node),
      });
      return;
    }
    if (request.type === 'reveal') {
      const { snapshot, graph } = await graphOn(request.spec.snapshot, request.day, request.id);
      const env = sceneEnv(snapshot, request.viewport);
      post({
        type: 'reveal',
        id: request.id,
        reveal: revealFlips(graph, request.spec, catalog, env, request.node),
      });
      return;
    }
    if (request.type === 'search' || request.type === 'locate') {
      if (request.id < latestSearch[request.type]) return;
      const ref = request.type === 'search' ? request.query.snapshot : request.query.spec.snapshot;
      if (ref === '') throw new DataError('no-snapshot', 'The search names no snapshot.');
      const found = await graphOn(ref, request.query.day, request.id);
      if (request.id < latestSearch[request.type]) return;
      post(
        request.type === 'search'
          ? { type: 'search', id: request.id, answer: answerSearch(request.query, found) }
          : {
              type: 'locate',
              id: request.id,
              answer: answerLocate(request.query, found, sceneEnv(found.snapshot, request.query.viewport)),
            },
      );
      return;
    }
    if (request.id < latestScene) return;
    const { spec } = request;
    if (spec.snapshot === '') throw new DataError('no-snapshot', 'The view names no snapshot.');
    const { base, loaded: drawn, tick } = await graphAt(spec.snapshot, spec.tick, request.id);
    const { snapshot, graph, console: links } = drawn;
    // A timeline the worker cannot work out (a stored history that does not read) leaves the timeline bar empty.
    const timeline = await ticks.info(spec.snapshot, base.snapshot).catch(() => undefined);
    // The day to compare with: built, or kept, like any day; its stages are not the page's to show. A day the
    // timeline no longer has (it would be drawn as the snapshot itself) or that cannot be read gives no diff.
    const since = request.diffFrom?.tick ?? undefined;
    const earlier =
      request.diffFrom === undefined
        ? null
        : await graphAt(spec.snapshot, since, -1).then(
            (found) => (found.tick === since ? found : null),
            () => null,
          );
    if (request.id < latestScene) return;
    post({ type: 'progress', id: request.id, stage: 'scene' });
    const scope = snapshot.scope.displayName ?? snapshot.scope.id;
    const env = sceneEnv(snapshot, request.viewport);
    const built = scenes.build(graph, spec, env);
    const { report } = built;
    let { scene } = built;
    let diff: TickDiff | undefined;
    if (earlier !== null && earlier.tick !== tick) {
      const compared = tickDiff({
        before: {
          snapshot: earlier.loaded.snapshot,
          graph: earlier.loaded.graph,
          ...(earlier.tick === undefined ? {} : { tick: earlier.tick }),
        },
        after: { snapshot, graph, ...(tick === undefined ? {} : { tick }) },
        spec,
        scene,
        report,
        catalog,
        envBefore: sceneEnv(earlier.loaded.snapshot, request.viewport),
        envAfter: env,
        build: scenes.build,
      });
      scene = compared.scene;
      diff = compared.diff;
    }
    post({
      type: 'scene',
      id: request.id,
      answer: {
        scene,
        report,
        source: {
          ref: spec.snapshot,
          scope,
          readTime: snapshot.readTime,
          assets: snapshot.assets.length,
          ...(tick === undefined ? {} : { tick }),
          ...(timeline === undefined ? {} : { timeline }),
        },
        lensTitle: catalog.lenses[spec.lens].title,
        icons: diagramIcons(scene),
        zoneTypes: zoneTypeNames(scene, graph),
        consoleLinks: consoleLinks(scene, links, environment.consoleTypes),
        ...(diff === undefined ? {} : { diff }),
      },
    });
    // Drawn without a diff on a stored history's timeline, with a chip: the next step's diff counts the chips against
    // this day's open view (diff/tickDiff.ts), so build it into the memo once the worker is idle.
    if (diff === undefined && timeline?.kind === 'history' && hasChip(scene)) {
      const open = openView(spec);
      warming = () => {
        scenes.build(graph, open, env);
      };
      armWarming();
    }
  };

  return (message: unknown): void => {
    const request = parseRequest(message);
    if (!('type' in request)) {
      post({ type: 'error', id: request.id, error: { code: 'protocol', message: request.error } });
      return;
    }
    received += 1;
    if (request.type === 'scene') {
      latestScene = Math.max(latestScene, request.id);
      // A new view: the open view of the one drawn before is not wanted any more.
      warming = null;
    }
    if (request.type === 'search' || request.type === 'locate') {
      latestSearch[request.type] = Math.max(latestSearch[request.type], request.id);
    }
    armWarming();
    queue = queue.then(
      () =>
        handle(request).catch((error: unknown) => {
          const code = error instanceof DataError ? error.code : 'internal';
          const text = error instanceof Error ? error.message : String(error);
          post({ type: 'error', id: request.id, error: { code, message: text } });
        }),
      () => undefined,
    );
  };
}

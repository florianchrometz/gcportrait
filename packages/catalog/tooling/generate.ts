/**
 * The two outputs of `pnpm catalog:build`: `dist/catalog.json` (for anything that wants a file) and
 * `src/generated/compiled-catalog.ts`, the module that `@gcportrait/catalog` exports as `catalog`. Both are
 * git-ignored build artefacts. The module holds the catalog as a constant typed `Catalog`: the compiler writes
 * only data that passed `CatalogSchema`, so the runtime exports it as it is, tsc holds it to the type, and
 * tooling/catalog.test.ts holds it to the schema and to a fresh compile.
 *
 * Why generated rather than committed: the package is consumed from source (its `exports` point at
 * src/index.ts) by Vite, Vitest, tsc and ESLint, so the module must exist before any of them runs. It is not
 * committed because every catalog change would regenerate one shared file that the catalog groups, authoring in
 * parallel, would all conflict on. `pnpm install` (the root `prepare` script) and the `typecheck`, `lint` and
 * `test` scripts that consume it build it first, and `pnpm catalog:check` fails if it is committed.
 *
 * Both are written plain, by `JSON.stringify` with a two-space indent, which is deterministic and readable as
 * it is: nothing formats the module (Prettier skips git-ignored files) and nothing lints it (eslint.config.js
 * ignores src/generated/), since nobody edits its data and tsc already holds it to `Catalog`.
 */
import type { Catalog } from '@gcportrait/model';

/** The catalog as two-space indented JSON, the text both outputs hold. */
function catalogText(catalog: Catalog): string {
  return JSON.stringify(catalog, null, 2);
}

/** The generated module's text: the header, the type import and the catalog as one constant. */
export function renderCatalogModule(catalog: Catalog, licenseId: string): string {
  return [
    `// SPDX-License-Identifier: ${licenseId}`,
    '// Generated by `pnpm catalog:build` from packages/catalog/products and packages/catalog/lenses; git-ignored.',
    '// Do not edit or commit: `pnpm catalog:check` fails while a file under src/generated/ is tracked.',
    "import type { Catalog } from '@gcportrait/model';",
    '',
    '/** The compiled catalog, which passed `CatalogSchema` when it was compiled; ../catalog.ts exports it. */',
    `export const CATALOG_DATA: Catalog = ${catalogText(catalog)};`,
    '',
  ].join('\n');
}

/** `dist/catalog.json`: the compiled catalog, two-space indented. */
export function renderCatalogJson(catalog: Catalog): string {
  return `${catalogText(catalog)}\n`;
}

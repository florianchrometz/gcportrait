/**
 * `archive-index.json`, written by vendor.mjs next to manifest.json: every SVG entry of each official archive
 * as it was when the icons were last vendored, with its SHA-256. It is the baseline `drift.mjs` compares a fresh
 * download with, so that a new, changed, renamed or removed icon shows up even when no vendored file uses it.
 */
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

import { ICONS_PAGE } from './archives.mjs';
import { PACKAGE_DIR } from './catalog-keys.mjs';

export const INDEX_PATH = path.join(PACKAGE_DIR, 'archive-index.json');

/**
 * @typedef {import('./mapping.mjs').SetName} SetName
 * @typedef {object} IndexedArchive
 * @property {string} url
 * @property {number} bytes
 * @property {string} sha256 of the whole archive (the same as manifest.json's `sources`)
 * @property {Record<string, string>} entries SVG entry name → SHA-256, in name order
 * @typedef {object} ArchiveIndex
 * @property {string} description
 * @property {string} page the library page that links the archives
 * @property {Record<SetName, IndexedArchive>} sources
 */

export const INDEX_DESCRIPTION =
  "Generated by scripts/vendor.mjs; do not edit by hand. Every SVG entry of each icon archive Google Cloud provides at https://cloud.google.com/icons, as it was when the icons were last vendored, with its SHA-256: the baseline scripts/drift.mjs compares a fresh download with (README 'Keeping the icons current'). The icons stay Google Cloud's; this file only lists them.";

/**
 * @param {Record<SetName, IndexedArchive>} sources
 * @returns {ArchiveIndex}
 */
export function archiveIndex(sources) {
  return { description: INDEX_DESCRIPTION, page: ICONS_PAGE, sources };
}

/**
 * @param {string} [file]
 * @returns {ArchiveIndex | undefined}
 */
export function readArchiveIndex(file = INDEX_PATH) {
  if (!existsSync(file)) return undefined;
  /** @type {unknown} */
  const document = JSON.parse(readFileSync(file, 'utf8'));
  return /** @type {ArchiveIndex} */ (document);
}
